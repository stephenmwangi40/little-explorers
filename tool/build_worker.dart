// Packs website/ into one Cloudflare Worker script (cloudflare/worker.js).
// Pages and CSS are inlined; images are served from the GitHub Pages copy.
// Run after tool/build_site.dart: dart run tool/build_worker.dart
import 'dart:convert';
import 'dart:io';

const imageOrigin = 'https://stephenmwangi40.github.io/little-explorers';

void main() {
  final root = Directory('website');
  final files = <String, String>{};
  for (final f in root.listSync(recursive: true).whereType<File>()) {
    final rel = '/${f.path.substring(root.path.length + 1).replaceAll(r'\', '/')}';
    if (rel.endsWith('.html') || rel.endsWith('.css')) {
      var key = rel.endsWith('/index.html') ? rel.substring(0, rel.length - 'index.html'.length) : rel;
      files[key] = f.readAsStringSync();
    }
  }
  final js = '''// Little Explorers information website (generated by tool/build_worker.dart).
const FILES = ${jsonEncode(files)};
const IMAGES = "$imageOrigin";
const SECURITY = {
  "x-content-type-options": "nosniff",
  "referrer-policy": "strict-origin-when-cross-origin",
  "x-frame-options": "DENY",
  "permissions-policy": "camera=(), microphone=(), geolocation=()",
};
export default {
  async fetch(request) {
    const url = new URL(request.url);
    let path = url.pathname;
    if (path !== "/" && !path.endsWith("/") && FILES[path + "/"]) {
      return Response.redirect(url.origin + path + "/" + url.search, 301);
    }
    if (path.startsWith("/assets/") && /\\.(png|jpg|svg|ico)\$/.test(path)) {
      const r = await fetch(IMAGES + path, { cf: { cacheTtl: 86400, cacheEverything: true } });
      const h = new Headers(r.headers);
      h.set("cache-control", "public, max-age=86400");
      return new Response(r.body, { status: r.status, headers: h });
    }
    const body = FILES[path];
    const type = path.endsWith(".css") ? "text/css; charset=utf-8" : "text/html; charset=utf-8";
    if (body !== undefined) {
      return new Response(body, { headers: { "content-type": type, "cache-control": "public, max-age=300", ...SECURITY } });
    }
    return new Response(FILES["/404.html"], { status: 404, headers: { "content-type": "text/html; charset=utf-8", ...SECURITY } });
  },
};
''';
  Directory('cloudflare').createSync();
  File('cloudflare/worker.js').writeAsStringSync(js);
  stdout.writeln('cloudflare/worker.js: ${js.length} bytes, ${files.length} files');
}
